"""Unit and hook-script tests for `.tasks/bin/guardrails.py`'s structural-edit checks and the
`PreToolUse`/`Edit|Write` hook that calls them (TASK-033).

Acceptance criteria this covers:
- an `Edit`/`Write` whose target range falls inside any generated region is denied
- an epic frontmatter edit changing `status` to anything but `wont-do` is denied
- edits outside both cases are unaffected
- the vendored copy of the hook script stays byte-identical to its canonical source
"""

import json
import subprocess
import sys
from pathlib import Path

import guardrails

REPO_ROOT = Path(__file__).resolve().parent.parent
HOOK_SCRIPT = REPO_ROOT / ".claude" / "hooks" / "pretooluse_edit_write.py"


# ---------------------------------------------------------------------------
# region_edit_violation -- pure, against text fixtures
# ---------------------------------------------------------------------------

EPIC_TEXT = (
    "---\nid: EPIC-001\ntitle: MVP\nspec: SPEC-001\nstatus: in-progress\n---\n\n"
    "## Goal\n\nSome prose here, outside any region.\n\n"
    "<!-- BEGIN:children (generated by sync — do not edit) -->\n"
    "| Task | Status | Title |\n|---|---|---|\n"
    "| TASK-001 | done | a |\n"
    "\n"
    "Progress: 1/1 done\n"
    "<!-- END:children -->\n"
)

BOARD_TEXT = (
    "# Board\n\n"
    "## Epics\n\n"
    "<!-- BEGIN:epics (generated by sync — do not edit) -->\n"
    "| Epic | Status | Progress |\n|---|---|---|\n"
    "| EPIC-001 | in-progress | 1/2 done |\n"
    "<!-- END:epics -->\n\n"
    "## TODO\n\n- TASK-002 — b\n\n"
    "## In Progress\n\n"
    "<!-- BEGIN:in-progress (generated by sync — do not edit) -->\n_(none)_\n<!-- END:in-progress -->\n\n"
    "## Done\n\n"
    "<!-- BEGIN:done (generated by sync — do not edit) -->\n_(none)_\n<!-- END:done -->\n"
)


def test_region_edit_violation_none_when_region_content_is_unchanged():
    new_text = EPIC_TEXT.replace("Some prose here", "Some *different* prose here")
    assert guardrails.region_edit_violation("EPIC-001-x.md", EPIC_TEXT, new_text) is None


def test_region_edit_violation_flags_a_changed_region_body():
    new_text = EPIC_TEXT.replace("| TASK-001 | done | a |", "| TASK-001 | done | a hand-edited row |")
    assert guardrails.region_edit_violation("EPIC-001-x.md", EPIC_TEXT, new_text) == "children"


def test_region_edit_violation_flags_removed_markers():
    new_text = EPIC_TEXT.replace(
        "<!-- BEGIN:children (generated by sync — do not edit) -->\n"
        "| Task | Status | Title |\n|---|---|---|\n"
        "| TASK-001 | done | a |\n"
        "\n"
        "Progress: 1/1 done\n"
        "<!-- END:children -->\n",
        "",
    )
    assert guardrails.region_edit_violation("EPIC-001-x.md", EPIC_TEXT, new_text) == "children"


def test_region_edit_violation_identifies_the_right_board_region():
    new_text = BOARD_TEXT.replace("_(none)_\n<!-- END:done -->", "| TASK-099 | x | y | z |\n<!-- END:done -->")
    assert guardrails.region_edit_violation("BOARD.md", BOARD_TEXT, new_text) == "done"


def test_region_edit_violation_none_for_todo_edits():
    # TODO is hand-maintained, never a BEGIN/END region -- editing it is never a violation here.
    new_text = BOARD_TEXT.replace("- TASK-002 — b", "- TASK-002 — b (reordered)")
    assert guardrails.region_edit_violation("BOARD.md", BOARD_TEXT, new_text) is None


def test_region_edit_violation_none_for_a_file_with_no_known_regions():
    assert guardrails.region_edit_violation("TASK-001-x.md", "---\nid: TASK-001\n---\nbody\n", "different\n") is None


