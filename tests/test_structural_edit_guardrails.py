# ---------------------------------------------------------------------------
# The hook script itself, as a real subprocess -- the documented `PreToolUse` stdin shape
# ---------------------------------------------------------------------------


def _run_hook(payload: dict) -> subprocess.CompletedProcess:
    return subprocess.run(
        [sys.executable, str(HOOK_SCRIPT)], input=json.dumps(payload), capture_output=True, text=True
    )


def _payload(tool_name: str, tool_input: dict, cwd: str) -> dict:
    return {
        "session_id": "test-session", "cwd": cwd, "hook_event_name": "PreToolUse",
        "tool_name": tool_name, "tool_input": tool_input,
    }


def test_hook_script_denies_an_edit_inside_a_generated_region(tmp_path):
    path = tmp_path / "EPIC-001-x.md"
    path.write_text(EPIC_TEXT)
    payload = _payload(
        "Edit",
        {"file_path": str(path), "old_string": "Progress: 1/1 done", "new_string": "Progress: 2/2 done"},
        str(tmp_path),
    )
    result = _run_hook(payload)
    assert result.returncode == 2
    assert "children" in result.stderr


def test_hook_script_denies_an_epic_status_hand_set_via_write(tmp_path):
    path = tmp_path / "EPIC-001-x.md"
    path.write_text(EPIC_TEXT)
    new_text = EPIC_TEXT.replace("status: in-progress", "status: todo")
    payload = _payload("Write", {"file_path": str(path), "content": new_text}, str(tmp_path))
    result = _run_hook(payload)
    assert result.returncode == 2
    assert "'todo'" in result.stderr


def test_hook_script_allows_wont_do_via_write(tmp_path):
    path = tmp_path / "EPIC-001-x.md"
    path.write_text(EPIC_TEXT)
    new_text = EPIC_TEXT.replace("status: in-progress", "status: wont-do")
    payload = _payload("Write", {"file_path": str(path), "content": new_text}, str(tmp_path))
    result = _run_hook(payload)
    assert result.returncode == 0
    assert result.stdout == ""
    assert result.stderr == ""


def test_hook_script_allows_an_edit_outside_any_region(tmp_path):
    path = tmp_path / "EPIC-001-x.md"
    path.write_text(EPIC_TEXT)
    payload = _payload(
        "Edit", {"file_path": str(path), "old_string": "## Goal", "new_string": "## Goal (renamed)"}, str(tmp_path)
    )
    result = _run_hook(payload)
    assert result.returncode == 0
    assert result.stdout == ""


def test_hook_script_ignores_non_edit_write_tool_calls():
    result = _run_hook(_payload("Bash", {"command": "ls"}, "/nonexistent"))
    assert result.returncode == 0
    assert result.stdout == ""


