def test_hook_against_this_repos_real_tree_reports_the_workflow_guidelines():
    result = _run_hook(_payload(str(REPO_ROOT)))
    assert result.returncode == 0
    parsed = json.loads(result.stdout)
    context = parsed["hookSpecificOutput"]["additionalContext"]
    assert "## Board state" in context
    assert "## Workflow guidelines (.tasks/guidelines.md)" in context


