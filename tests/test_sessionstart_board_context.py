def test_build_context_none_when_tasks_dir_absent(tmp_path):
    assert sessionstart_board_context.build_context(tmp_path / ".tasks") is None


def test_build_context_includes_board_columns_with_no_in_flight_task(tmp_path):
    tasks_root = tmp_path / ".tasks"
    tasks_root.mkdir()
    _sync_bin(tasks_root)
    _write_board(tasks_root)
    context = sessionstart_board_context.build_context(tasks_root)
    assert "### In Progress" in context
    assert "### In Review" in context
    assert "## Current task" not in context


def test_build_context_includes_current_task_summary_when_in_progress(tmp_path):
    tasks_root = tmp_path / ".tasks"
    tasks_root.mkdir()
    _sync_bin(tasks_root)
    _write_board(tasks_root, in_progress="| TASK-001 | a | — | task-001-a |")
    _write_task(tasks_root, "TASK-001", "a", "in-progress", branch="task-001-a")
    context = sessionstart_board_context.build_context(tasks_root)
    assert "## Current task" in context
    assert "- id: TASK-001" in context
    assert "- status: in-progress" in context
    assert "- pr: none yet" in context


def test_build_context_includes_pr_when_in_review(tmp_path):
    tasks_root = tmp_path / ".tasks"
    tasks_root.mkdir()
    _sync_bin(tasks_root)
    _write_board(tasks_root, in_review="| TASK-002 | b | — | https://example.com/pr/2 |")
    _write_task(
        tasks_root, "TASK-002", "b", "in-review", branch="task-002-b", pr="https://example.com/pr/2"
    )
    context = sessionstart_board_context.build_context(tasks_root)
    assert "- status: in-review" in context
    assert "- pr: https://example.com/pr/2" in context


def test_build_context_includes_guidelines_verbatim(tmp_path):
    tasks_root = tmp_path / ".tasks"
    tasks_root.mkdir()
    _sync_bin(tasks_root)
    _write_board(tasks_root)
    (tasks_root / "guidelines.md").write_text("# Workflow guidelines\n\nSome specific text.\n")
    context = sessionstart_board_context.build_context(tasks_root)
    assert "## Workflow guidelines (.tasks/guidelines.md)" in context
    assert "Some specific text." in context


def test_build_context_omits_guidelines_section_when_absent_but_keeps_board(tmp_path):
    tasks_root = tmp_path / ".tasks"
    tasks_root.mkdir()
    _sync_bin(tasks_root)
    _write_board(tasks_root, in_progress="| TASK-003 | c | — | task-003-c |")
    _write_task(tasks_root, "TASK-003", "c", "in-progress", branch="task-003-c")
    context = sessionstart_board_context.build_context(tasks_root)
    assert "Workflow guidelines" not in context
    assert "### In Progress" in context
    assert "## Current task" in context


def test_build_context_none_when_tasks_dir_exists_but_is_entirely_empty(tmp_path):
    tasks_root = tmp_path / ".tasks"
    tasks_root.mkdir()
    assert sessionstart_board_context.build_context(tasks_root) is None


