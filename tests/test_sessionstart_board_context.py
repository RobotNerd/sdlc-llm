"""Unit and hook-script tests for `.claude/hooks/sessionstart_board_context.py` (TASK-037):
injects `BOARD.md`'s `In Progress`/`In Review` regions, an in-flight task summary, and
`.tasks/guidelines.md` into `SessionStart`'s `additionalContext`.

Acceptance criteria this covers:
- no in-flight task -> board's open columns only
- an in-flight task -> also its id/title/status/pr
- `guidelines.md`'s contents appear alongside the board state
- silent (no output) if `.tasks/` doesn't exist
- still works (board context, no guidelines section) if `.tasks/` exists but `guidelines.md`
  doesn't
"""

import importlib.util
import json
import subprocess
import sys
from importlib.machinery import SourceFileLoader
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
SCRIPT_PATH = REPO_ROOT / ".claude" / "hooks" / "sessionstart_board_context.py"

_loader = SourceFileLoader("sessionstart_board_context", str(SCRIPT_PATH))
_spec = importlib.util.spec_from_loader("sessionstart_board_context", _loader)
sessionstart_board_context = importlib.util.module_from_spec(_spec)
sys.modules["sessionstart_board_context"] = sessionstart_board_context
_loader.exec_module(sessionstart_board_context)


_BOARD_TEMPLATE = (
    "# Board\n\n"
    "## In Progress\n\n"
    "<!-- BEGIN:in-progress (generated by sync — do not edit) -->\n{in_progress}\n<!-- END:in-progress -->\n\n"
    "## In Review\n\n"
    "<!-- BEGIN:in-review (generated by sync — do not edit) -->\n{in_review}\n<!-- END:in-review -->\n"
)

_TASK_TEMPLATE = (
    "---\nid: {id}\ntitle: {title}\nstatus: {status}\nepic: null\n"
    "branch: {branch}\npr: {pr}\nblocked_by: []\nblocks: []\n---\n"
)


def _write_board(tasks_root: Path, in_progress: str = "_(none)_", in_review: str = "_(none)_") -> None:
    (tasks_root / "BOARD.md").write_text(_BOARD_TEMPLATE.format(in_progress=in_progress, in_review=in_review))


def _write_task(tasks_root: Path, task_id: str, title: str, status: str, branch: str, pr: str | None = None) -> None:
    pr_value = "null" if pr is None else f'"{pr}"'
    (tasks_root / f"{task_id}-{title.lower().replace(' ', '-')}.md").write_text(
        _TASK_TEMPLATE.format(id=task_id, title=title, status=status, branch=f'"{branch}"', pr=pr_value)
    )


def _sync_bin(tasks_root: Path) -> None:
    """A real, minimal copy of `.tasks/bin/sync` so `_load_sync` can load it -- copying the
    actual file keeps this test honest against the real region/discover implementation rather
    than a hand-rolled stand-in.
    """
    (tasks_root / "bin").mkdir(parents=True, exist_ok=True)
    (tasks_root / "bin" / "sync").write_text((REPO_ROOT / ".tasks" / "bin" / "sync").read_text())


