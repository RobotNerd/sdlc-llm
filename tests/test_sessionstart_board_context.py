# main() -- hook-script, real subprocess
# ---------------------------------------------------------------------------


def _payload(cwd: str, hook_event_name: str = "SessionStart", source: str = "startup") -> dict:
    return {
        "session_id": "test-session", "cwd": cwd, "hook_event_name": hook_event_name, "source": source,
    }


def _run_hook(payload: dict) -> subprocess.CompletedProcess:
    return subprocess.run(
        [sys.executable, str(SCRIPT_PATH)], input=json.dumps(payload), capture_output=True, text=True
    )


def test_hook_silent_when_tasks_dir_absent(tmp_path):
    result = _run_hook(_payload(str(tmp_path)))
    assert result.returncode == 0
    assert result.stdout == ""
    assert result.stderr == ""


def test_hook_ignores_a_non_session_start_event(tmp_path):
    tasks_root = tmp_path / ".tasks"
    tasks_root.mkdir()
    _sync_bin(tasks_root)
    _write_board(tasks_root, in_progress="| TASK-001 | a | — | task-001-a |")
    result = _run_hook(_payload(str(tmp_path), hook_event_name="PreToolUse"))
    assert result.returncode == 0
    assert result.stdout == ""


def test_hook_survives_malformed_json_on_stdin():
    result = subprocess.run(
        [sys.executable, str(SCRIPT_PATH)], input="not json", capture_output=True, text=True
    )
    assert result.returncode == 0
    assert result.stdout == ""


def test_hook_output_matches_the_documented_session_start_schema(tmp_path):
    """The exact shape Claude Code's `SessionStart` hooks are documented to emit:
    `{"hookSpecificOutput": {"hookEventName": "SessionStart", "additionalContext": <str>}}`,
    and nothing else on stdout (stdout must contain only the JSON object).
    """
    tasks_root = tmp_path / ".tasks"
    tasks_root.mkdir()
    _sync_bin(tasks_root)
    _write_board(tasks_root, in_progress="| TASK-001 | a | — | task-001-a |")
    _write_task(tasks_root, "TASK-001", "a", "in-progress", branch="task-001-a")
    result = _run_hook(_payload(str(tmp_path)))
    assert result.returncode == 0
    parsed = json.loads(result.stdout)
    assert set(parsed.keys()) == {"hookSpecificOutput"}
    hook_output = parsed["hookSpecificOutput"]
    assert hook_output["hookEventName"] == "SessionStart"
    assert isinstance(hook_output["additionalContext"], str)
    assert "TASK-001" in hook_output["additionalContext"]


