def test_load_config_missing_file_returns_empty_dict(tmp_path):
    assert load_config(tmp_path) == {}


def test_load_config_parses_real_fields(tmp_path):
    (tmp_path / "config.md").write_text("---\narchive_done: false\ntest_command: pytest\n---\n")
    config = load_config(tmp_path)
    assert config == {"archive_done": False, "test_command": "pytest"}


def test_load_config_feeds_should_auto_archive(tmp_path):
    (tmp_path / "config.md").write_text("---\narchive_done: false\n---\n")
    assert should_auto_archive(load_config(tmp_path)) is False
