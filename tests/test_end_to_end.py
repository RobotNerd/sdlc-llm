def test_archive_moves_done_and_wont_do_and_next_id_accounts_for_them(repo):
    run_sync(repo)

    assert (repo / "archive" / "TASK-001-x.md").is_file()
    assert (repo / "archive" / "TASK-006-x.md").is_file()
    assert not (repo / "TASK-001-x.md").exists()
    assert not (repo / "TASK-006-x.md").exists()

    assert next_id(repo, "task") == "TASK-009"  # accounts for the 8 that exist, 6 archived or not
